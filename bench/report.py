"""Render measured offline run JSON files into the checked-in baseline report."""

from __future__ import annotations

import json
from pathlib import Path
import sys

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from bench.data import NAMES, ROOT


def render_report(out_dir: Path = ROOT / "out") -> str:
    """Include metrics, oracle thresholds, blocking loss, denominators and measured runtime."""
    reports = []
    for name in NAMES:
        path = Path(out_dir) / f"{name}.json"
        if not path.exists():
            raise ValueError(f"missing {path}; run uv run python bench/run.py --dataset {name} first")
        reports.append(json.loads(path.read_text()))
    lines = [
        "# Offline baseline measurements", "",
        "Generated by `uv run python bench/report.py` from `bench/out/*.json`. "
        "These historical in-sample tables are separate from the held-out protocol in "
        "[EVALUATION.md](EVALUATION.md) and measured [EVIDENCE.md](EVIDENCE.md). "
        "Separate cached live-pass status is recorded below.", "",
        "Jaro-Winkler and TF-IDF thresholds maximize F1 on the **same truth being scored**. "
        "They are in-sample upper bounds for these fixed best-match methods, not held-out accuracy "
        "estimates or general upper bounds for string matching. Threshold tuning evaluates all distinct "
        "scores, keeps ties together, and prefers fewer links when F1 ties.", "",
        "Both similarity baselines choose one right record per left; several left records may choose "
        "the same right record. Ties select the earliest right source row. Their recall is consequently "
        "limited on truth with multiple right matches per left. Exact matching emits every pair equal "
        "after `fields.normalize` in every `on` field; a missing or empty field prevents a match. "
        "Scoring counts unique ID pairs and uses zero for rates with an empty denominator.", "",
        "Jaro-Winkler compares joined normalized `on` fields only within nonempty shared first-character "
        "blocks. TF-IDF fits character 2–4-grams jointly on left and right, compares positive cosine "
        "pairs using sparse row chunks, and selects the best per left. Fields have no tuned weights. "
        "The first-character rule can lose true matches; the table reports that loss explicitly.", "",
        "## Dataset sizes", "",
        "| Dataset | Left | Right | Truth pairs | Sample | Fields |",
        "|---|---:|---:|---:|---|---|",
    ]
    for report in reports:
        counts = report["evaluated_counts"]
        sample = report["sample"]["requested_left_records"]
        fields = ", ".join(str(field) for field in report["on"])
        sampling = "full" if sample is None else f"{sample}; seed 0"
        lines.append(f"| {report['dataset']} | {counts['left']:,} | {counts['right']:,} | "
                     f"{counts['truth']:,} | {sampling} | {fields} |")
    lines += ["", "## Precision, recall and F1", "",
              "All rates are percentages. Thresholds are cosine or Jaro-Winkler similarities, "
              "not probabilities. "
              "A dash means that rejecting every pair maximized F1.", "",
              "| Dataset | Method | Precision | Recall | F1 | TP | FP | FN | Threshold | Seconds |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    labels = {"exact": "Exact", "jaro_winkler": "Jaro-Winkler (oracle)", "tfidf_cosine": "TF-IDF (oracle)"}
    for report in reports:
        for key, result in report["baselines"].items():
            m = result["metrics"]
            threshold = "—" if result["threshold"] is None else f"{result['threshold']:.6f}"
            lines.append(f"| {report['dataset']} | {labels[key]} | {100*m['precision']:.2f} | "
                         f"{100*m['recall']:.2f} | {100*m['f1']:.2f} | {m['tp']:,} | {m['fp']:,} | "
                         f"{m['fn']:,} | {threshold} | {result['seconds']:.3f} |")
    lines += ["", "## Blocking available to each similarity baseline", "",
              "Blocking recall is measured before best-match selection and thresholding. "
              "Best-match recall is the share of truth surviving the one-best-right choice before "
              "thresholding. Candidate counts describe scored pairs, not the number of predictions.", "",
              "| Dataset | Method | Candidate pairs | Blocking recall | Best-match recall |",
              "|---|---|---:|---:|---:|"]
    for report in reports:
        for key in ("jaro_winkler", "tfidf_cosine"):
            result = report["baselines"][key]
            lines.append(f"| {report['dataset']} | {labels[key]} | {result['candidate_count']:,} | "
                         f"{100*result['blocking_recall']:.2f} | {100*result['best_match_recall']:.2f} |")
    lines += ["", "## Data checks and interpretation", ""]
    for report in reports:
        meta = report["meta"]
        checks = meta["validation"]
        lines += [f"- **{report['dataset']}**: {meta['definition']} "
                  f"Duplicate truth pairs removed: {checks['truth_duplicate_pairs']}; "
                  f"duplicate records excluding ID, left/right: "
                  f"{checks['left_duplicate_records_excluding_id']}/"
                  f"{checks['right_duplicate_records_excluding_id']}. "
                  "IDs are unique within each source and every truth ID was verified."]
    lines += ["",
              "DBLP-ACM's downloaded DBLP2.csv has 2,616 rows; the Leipzig web page says 2,614. "
              "This report uses the actual archive without silently deleting records. Product mappings "
              "include multiple matches, and identical descriptions under different IDs are retained.", "",
              "NBER firm links include parent/subsidiary and historical associations. The prepared set "
              "contains only labeled companies. The historical oracle tables above treated unlisted pairs "
              "as negative by assumption; those pairs are **not verified negatives**, and the resulting "
              "precision/F1 measure crosswalk agreement rather than established match accuracy. "
              "The new held-out harness leaves unlisted NBER predictions unknown and does not tune F1. See "
              "[FIRM_DATA.md](FIRM_DATA.md) for the search, terms, construction, and limitations. "
              "All sources and download hashes are recorded in each dataset's meta.json.", "",
              "Exact matching can have zero product recall because prices and descriptions differ or "
              "are missing. Jaro-Winkler is especially weak on Abt-Buy's concatenated descriptions. "
              "The reported results use the declared fields without dataset-specific similarity weights.", "",
              "## jlink integration and runtime", ""]
    for report in reports:
        blocking = report["blocking"]
        detail = blocking.get("reason", f"{blocking.get('candidate_count', 0):,} candidates")
        lines.append(f"- {report['dataset']}: jlink blocking **{blocking['status']}** ({detail}); "
                     f"live **{report['live']['status']}**; total {report['seconds']:.3f} seconds; "
                     f"run {report['created_at']}.")
    lines += ["", "### Separate saved live runs", "",
              "These are existing artifacts, not new API calls or held-out measurements. "
              "They were not part of the older offline runner's `live` status. "
              "Counts and costs below come directly from each saved `result.json`.", "",
              "| Dataset | Model | Candidate pairs | New calls in saved run | Cached decisions | Cost USD |",
              "|---|---|---:|---:|---:|---:|"]
    for report in reports:
        path = Path(out_dir) / "live" / report["dataset"] / "result.json"
        if path.exists():
            live = json.loads(path.read_text())
            lines.append(f"| {report['dataset']} | {live['model']} | {live['pairs']:,} | "
                         f"{live['calls']:,} | {live['cached']:,} | {live['dollars']:.4f} |")
        else:
            lines.append(f"| {report['dataset']} | no saved run found | — | — | — | — |")
    environment = reports[0]["environment"]
    packages = ", ".join(f"{name} {version}" for name, version in environment["packages"].items())
    lines += ["", f"Measured on {environment['platform']}; Python {environment['python']}. "
              "Timings include baseline similarity construction and threshold tuning, exclude data download "
              "and parquet loading, and are single-run wall times "
              "rather than controlled speed comparisons.", "",
              "Packages: " + packages + ".", "", "Reproduce full runs:", "", "```sh",
              "uv sync --group bench", "uv run python bench/prepare.py",
              "for name in febrl4 dblp-acm abt-buy amazon-google nber-firms; do",
              "  uv run python bench/run.py --dataset \"$name\" --budget 0.10", "done",
              "uv run python bench/report.py", "```", "",
              "The harness writes one JSON file per dataset, so a sampled rerun replaces that dataset's "
              "previous report. Sampling is explicit in JSON and this table; rerun without `--sample` to "
              "restore full-data measurements. `--sample 1000` keeps all right-side competitors and uses "
              "seed 0. No current dataset has more than 60,000 left-times-10 possible candidates.", ""]
    return "\n".join(lines)


def main() -> int:
    try:
        report = render_report()
    except (ValueError, OSError) as exc:
        print(f"report: {exc}", file=sys.stderr)
        return 2
    (ROOT / "BASELINES.md").write_text(report)
    print(f"Wrote {ROOT / 'BASELINES.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
